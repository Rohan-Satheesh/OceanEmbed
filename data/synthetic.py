"""Synthetic stand-in for the harmonized OceanEmbed store (demo build, Chunks 4-8).

Writes the same groups/variables/grid/depths/`*_mask` channels as the real pipeline
(sst, sss, ssh, currents, winds, glorys) into `<out>/zarr/oceanembed.zarr` — the same layout as
`data/processed/` — so the demo is switched between real and synthetic data purely by config
(`paths.processed_dir`, see configs/demo.yaml). It must never write into the real processed dir.

The fields are physically *motivated*, not calibrated: monsoon-driven winds and SST, a western
Arabian Sea upwelling cooling, a fresh Bay of Bengal plume, mesoscale eddies that drive SSH, SST,
geostrophic currents and thermocline depth, and a subsurface temperature profile (mixed layer +
thermocline) whose depth follows SSH. That gives a learnable surface -> subsurface signal.
Scores on this data only show the pipeline works end to end, never real-ocean skill.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd
import xarray as xr
from scipy.ndimage import distance_transform_edt, gaussian_filter

from data.catalog import Channel, Domain, load_base_config
from data.harmonize import append_zarr

REPO_ROOT = Path(__file__).resolve().parents[1]
BANNER = "SYNTHETIC DATA - generated by data/synthetic.py; NOT real observations"
ORIGIN = np.datetime64("2021-01-01")   # eddy clock origin: fields depend on absolute date only
SPAN_DAYS = 1600
N_EDDIES = 300
G = 9.81
OMEGA = 7.292e-5

CHANNELS = {
    "sst": ["analysed_sst"],
    "sss": ["sos"],
    "ssh": ["adt", "sla"],
    "currents": ["u", "v", "ug", "vg"],
    "winds": ["uwnd", "vwnd", "ws", "nobs"],
    "glorys": ["thetao"],
}


# ---------------------------------------------------------------------------------------- geography
def make_grid(domain: Domain) -> tuple[np.ndarray, np.ndarray]:
    n_lat = int(round((domain.lat_max - domain.lat_min) / domain.resolution_deg)) + 1
    n_lon = int(round((domain.lon_max - domain.lon_min) / domain.resolution_deg)) + 1
    return (domain.lat_min + domain.resolution_deg * np.arange(n_lat),
            domain.lon_min + domain.resolution_deg * np.arange(n_lon))


def _crude_sea_mask(lat: np.ndarray, lon: np.ndarray) -> np.ndarray:
    """Fallback coastline when the real bathymetry file isn't present (fresh clone)."""
    from matplotlib.path import Path as MPath
    lon2, lat2 = np.meshgrid(lon, lat)
    pts = np.column_stack([lon2.ravel(), lat2.ravel()])
    land = np.zeros(len(pts), dtype=bool)
    for poly in (
        [(66, 25), (68, 30.5), (105, 30.5), (105, 22), (100, 16), (98, 8), (100, 5), (101, 5), (88, 24),
         (86, 20), (80, 15), (80, 10), (77, 8), (73, 17), (72.5, 21), (68, 22.5)],   # India + Asia
        [(45, 30.5), (60, 30.5), (58, 22), (52, 16), (45, 13)],                       # Arabia
        [(45, 5), (51.5, 5), (51.5, 12), (44, 12.5), (45, 11)],                       # Horn of Africa
    ):
        land |= MPath(poly).contains_points(pts)
    return ~land.reshape(lat2.shape)


def load_geography(lat: np.ndarray, lon: np.ndarray, processed_dir: Path | None = None) -> tuple[np.ndarray, np.ndarray]:
    """(sea_mask bool[lat,lon], seafloor_depth_m float[lat,lon]) — real ETOPO-derived if available."""
    real = (processed_dir or REPO_ROOT / "data" / "processed") / "bathymetry" / "land_sea_mask.nc"
    if real.exists():
        ds = xr.open_dataset(real).reindex(lat=lat, lon=lon, method="nearest")
        sea = ds["sea_mask"].values.astype(bool)
        depth = np.where(sea, np.nan_to_num(ds["seafloor_depth_m"].values, nan=50.0), np.nan)
        return sea, np.maximum(depth, 5.0)
    sea = _crude_sea_mask(lat, lon)
    dist = distance_transform_edt(sea)                  # cells to nearest land
    depth = np.where(sea, np.minimum(5000.0, 30.0 + 260.0 * dist ** 1.4), np.nan)
    return sea, depth


# ------------------------------------------------------------------------------------- field pieces
def _eddy_params(seed: int) -> dict[str, np.ndarray]:
    rng = np.random.default_rng(seed)
    return dict(
        birth=rng.uniform(-150, SPAN_DAYS, N_EDDIES), life=rng.uniform(60, 180, N_EDDIES),
        lat0=rng.uniform(6, 29, N_EDDIES), lon0=rng.uniform(46, 104, N_EDDIES),
        vlon=-rng.uniform(0.02, 0.07, N_EDDIES), vlat=rng.normal(0, 0.012, N_EDDIES),
        amp=rng.choice([-1.0, 1.0], N_EDDIES) * rng.uniform(0.06, 0.20, N_EDDIES),   # metres of SLA
        rad=rng.uniform(1.0, 2.2, N_EDDIES),
    )


def _sla_eddies(day: float, p: dict, lat2: np.ndarray, lon2: np.ndarray) -> np.ndarray:
    age = day - p["birth"]
    act = (age >= 0) & (age <= p["life"])
    out = np.zeros_like(lat2)
    for i in np.flatnonzero(act):
        env = np.sin(np.pi * age[i] / p["life"][i])
        dlat = lat2 - (p["lat0"][i] + p["vlat"][i] * age[i])
        dlon = (lon2 - (p["lon0"][i] + p["vlon"][i] * age[i])) * np.cos(np.deg2rad(lat2))
        out += p["amp"][i] * env * np.exp(-(dlat ** 2 + dlon ** 2) / (2 * p["rad"][i] ** 2))
    return out


def _smooth_noise(rng: np.random.Generator, shape: tuple[int, int], sigma: float, scale: float) -> np.ndarray:
    n = gaussian_filter(rng.standard_normal(shape), sigma)
    return scale * n / (n.std() + 1e-9)


def _daily_rng(seed: int, day: int, salt: int) -> np.random.Generator:
    return np.random.default_rng([seed, int(day) + 10_000, salt])


def _coast_band(sea: np.ndarray, cells: int) -> np.ndarray:
    """True for ocean cells within `cells` grid cells of land."""
    return sea & (distance_transform_edt(sea) <= cells)


def compute_day(day: np.datetime64, lat: np.ndarray, lon: np.ndarray, sea: np.ndarray, floor_m: np.ndarray,
                depths: np.ndarray, eddies: dict, seed: int) -> dict[str, np.ndarray]:
    """All fields for one day, deterministic in (day, seed) only — independent of chunking."""
    d = int((day - ORIGIN) / np.timedelta64(1, "D"))
    doy = int(pd.Timestamp(day).dayofyear)
    th = 2 * np.pi * (doy - 1) / 365.25
    lon2, lat2 = np.meshgrid(lon, lat)
    shape = lat2.shape
    mon = np.exp(-(((doy - 215) / 40.0) ** 2))                    # SW-monsoon bump (JJAS)
    m = np.cos(th - 2 * np.pi * 205 / 365.25)                     # +1 SW monsoon, -1 NE monsoon

    # sea-level anomaly / absolute dynamic topography
    sla = (_sla_eddies(d, eddies, lat2, lon2)
           + 0.06 * np.sin(th - 1.0) * np.exp(-((lat2 - 12) / 10) ** 2)
           + _smooth_noise(_daily_rng(seed, d, 1), shape, 4, 0.01))
    mdt = 0.7 + 0.35 * np.exp(-((lat2 - 9) / 7) ** 2)
    adt = mdt + sla

    # winds
    g = np.exp(-((lat2 - 12) / 12) ** 2)
    jet = 1.0 + 0.8 * np.exp(-(((lat2 - 12) / 5) ** 2 + ((lon2 - 55) / 6) ** 2))       # Somali-jet enhancement
    rw = _daily_rng(seed, d, 2)
    uwnd = g * jet * (2.0 * m + 4.5 * max(m, 0.0)) + _smooth_noise(rw, shape, 5, 1.2)
    vwnd = g * jet * (1.5 * m + 1.5 * max(m, 0.0)) + _smooth_noise(rw, shape, 5, 1.0)
    ws = np.hypot(uwnd, vwnd)

    # SST: latitudinal + seasonal + upwelling + eddy signal
    amp = 3.0 * np.clip((lat2 - 8) / 20, 0, 1)
    upw = 3.2 * mon * np.exp(-(((lat2 - 14) / 6) ** 2 + ((lon2 - 57) / 4.5) ** 2))
    sst = (29.8 - 0.14 * np.maximum(lat2 - 10, 0) + amp * np.cos(th - 2 * np.pi * 125 / 365.25)
           - upw + 5.0 * sla + _smooth_noise(_daily_rng(seed, d, 3), shape, 3, 0.15))
    sst = np.clip(sst, 15.0, 34.0)

    # SSS: fresh Bay of Bengal plume (peaks Sep-Nov), salty northern Arabian Sea
    fresh = 0.5 + 0.5 * np.cos(th - 2 * np.pi * 270 / 365.25)
    sos = (35.4 - 3.2 * fresh * np.exp(-(((lat2 - 18) / 5) ** 2 + ((lon2 - 89) / 5) ** 2))
           + 1.4 * np.exp(-((lat2 - 24) / 4) ** 2) * (lon2 < 68) + _smooth_noise(_daily_rng(seed, d, 4), shape, 3, 0.1))
    sos = np.clip(sos, 28.0, 38.0)

    # geostrophic + Ekman currents
    f = 2 * OMEGA * np.sin(np.deg2rad(np.maximum(lat2, 5.0)))
    dy = np.deg2rad(lat[1] - lat[0]) * 6.371e6
    dx = dy * np.cos(np.deg2rad(lat2))
    dadt_dy, dadt_dx = np.gradient(adt, dy, axis=0), np.gradient(adt, axis=1) / dx
    ug = np.clip(-G / f * dadt_dy, -1.5, 1.5)
    vg = np.clip(G / f * dadt_dx, -1.5, 1.5)
    u, v = ug + 0.02 * (uwnd + vwnd) / np.sqrt(2), vg + 0.02 * (vwnd - uwnd) / np.sqrt(2)

    # subsurface temperature: mixed layer + thermocline whose depth follows SSH and upwelling
    D = np.clip(110.0 + 450.0 * sla - 70.0 * upw / 3.2, 25.0, 300.0)
    w = 0.35 * D + 10.0
    z = depths[:, None, None]
    tdeep = 6.5 + 13.0 * np.exp(-z / 420.0)      # deep profile roughly matches real GLORYS at 500/1000 m
    sig = lambda x: 1.0 / (1.0 + np.exp(-x))  # noqa: E731
    f_z = sig((D - z) / w) / sig(D / w)                             # equals 1 at z=0, decreasing with depth
    thetao = tdeep + (sst - tdeep) * f_z
    thetao += _smooth_noise(_daily_rng(seed, d, 5), shape, 3, 0.08)[None] * np.exp(-z / 400.0)

    # observation gaps (NaN + mask=0), coastal + blob patterns like the real products
    coast1, coast2 = _coast_band(sea, 1), _coast_band(sea, 2)
    r = _daily_rng(seed, d, 6)
    blobs = np.zeros(shape, bool)
    yy, xx = np.ogrid[:shape[0], :shape[1]]
    for _ in range(3):                                              # RFI-style SSS dropouts
        cy, cx, rr = r.integers(0, shape[0]), r.integers(0, shape[1]), r.integers(3, 8)
        blobs |= (yy - cy) ** 2 + (xx - cx) ** 2 <= rr ** 2
    obs = {"sst": sea, "sss": sea & ~coast2 & ~blobs, "ssh": sea & ~coast1,
           "currents": sea & ~coast1, "winds": sea}
    below = floor_m[None] < depths[:, None, None]
    nobs = np.clip(3.0 + _smooth_noise(_daily_rng(seed, d, 7), shape, 4, 0.7), 0, 4)
    raw = {
        "sst": {"analysed_sst": sst}, "sss": {"sos": sos},
        "ssh": {"adt": adt, "sla": sla}, "currents": {"u": u, "v": v, "ug": ug, "vg": vg},
        "winds": {"uwnd": uwnd, "vwnd": vwnd, "ws": ws, "nobs": nobs},
    }
    out: dict[str, np.ndarray] = {}
    for ch, vars_ in raw.items():
        for name, arr in vars_.items():
            out[f"{ch}/{name}"] = np.where(obs[ch], arr, np.nan).astype("float32")
    out["glorys/thetao"] = np.where(sea[None] & ~below, thetao, np.nan).astype("float32")
    return out


# ------------------------------------------------------------------------------------------ writing
def build_chunk(days: pd.DatetimeIndex, lat, lon, sea, floor_m, depths, eddies, seed) -> dict[str, xr.Dataset]:
    per_day = [compute_day(np.datetime64(d), lat, lon, sea, floor_m, depths, eddies, seed) for d in days]
    out: dict[str, xr.Dataset] = {}
    for ch, vars_ in CHANNELS.items():
        data = {}
        dims = ("time", "depth", "lat", "lon") if ch == "glorys" else ("time", "lat", "lon")
        coords = {"time": days.values, "lat": lat, "lon": lon}
        if ch == "glorys":
            coords["depth"] = depths.astype("float64")
        for name in vars_:
            arr = np.stack([day_fields[f"{ch}/{name}"] for day_fields in per_day])
            data[name] = (dims, arr)
            data[f"{name}_mask"] = (dims, (~np.isnan(arr)).astype("int8"))
        ds = xr.Dataset(data, coords=coords)
        ds.attrs.update(data_source="synthetic", synthetic_warning=BANNER)
        out[ch] = ds
    return out


def generate(start: str, end: str, out_dir: Path, domain: Domain, depths_m: list[int], seed: int = 42,
             processed_dir: Path | None = None, chunk_days: int = 30) -> Path:
    real_dir = (REPO_ROOT / "data" / "processed").resolve()
    if Path(out_dir).resolve() == real_dir:
        raise ValueError("refusing to write synthetic data into the real processed dir (data/processed)")
    lat, lon = make_grid(domain)
    sea, floor_m = load_geography(lat, lon, processed_dir)
    depths = np.asarray(depths_m, dtype=float)
    eddies = _eddy_params(seed)
    days = pd.date_range(start, end, freq="D")
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "SYNTHETIC_DATA.txt").write_text(BANNER + f"\nseed={seed}\nrange={start}..{end}\n", encoding="utf-8")
    for i in range(0, len(days), chunk_days):
        chunk = days[i:i + chunk_days]
        for ch, ds in build_chunk(chunk, lat, lon, sea, floor_m, depths, eddies, seed).items():
            append_zarr(ds, Channel(name=ch, label=ch, source="synthetic", variables=CHANNELS[ch],
                                    native_resolution_deg=domain.resolution_deg, units=""), out_dir)
        print(f"  generated {chunk[0].date()} .. {chunk[-1].date()}")
    return out_dir / "zarr" / "oceanembed.zarr"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate the synthetic demo store (never touches data/processed).")
    ap.add_argument("--config", default=str(REPO_ROOT / "configs" / "demo.yaml"), help="override YAML (default demo)")
    ap.add_argument("--start", default=None, help="default: first day of the demo train period")
    ap.add_argument("--end", default=None, help="default: last day of the demo test period")
    ap.add_argument("--seed", type=int, default=None)
    args = ap.parse_args(argv)
    cfg = load_base_config(override=args.config)
    if cfg.data_source != "synthetic":
        raise SystemExit("config data_source is not 'synthetic' — refusing to generate")
    start = args.start or cfg.periods["train"][0]
    end = args.end or cfg.periods["test"][1]
    out = REPO_ROOT / cfg.paths["processed_dir"]
    print(f"{BANNER}\n{start} .. {end} -> {out}")
    print("store:", generate(start, end, out, cfg.domain, cfg.depths_m, cfg.seed if args.seed is None else args.seed))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
